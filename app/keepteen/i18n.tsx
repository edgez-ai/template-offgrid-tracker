export const languages = [
  { code: "en", nativeName: "English", table: en as Table },
  { code: "zh-Hans", nativeName: "简体中文", table: zhHans },
] as const;
export type LanguageCode = (typeof languages)[number]["code"];

const languageStorageKey = "keepteen.language.v1";

function deviceLanguage(): LanguageCode {
  const locale: string = Platform.OS === "ios"
    ? NativeModules.SettingsManager?.settings?.AppleLocale ?? NativeModules.SettingsManager?.settings?.AppleLanguages?.[0] ?? ""
    : NativeModules.I18nManager?.localeIdentifier ?? "";
  return locale.toLowerCase().startsWith("zh") ? "zh-Hans" : "en";
}

type Vars = Record<string, string | number>;
type I18nValue = {
  language: LanguageCode;
  setLanguage: (code: LanguageCode) => void;
  t: (key: MessageKey, vars?: Vars) => string;
  formatAgo: (timestampMs: number) => string;
  formatDateTime: (timestampMs: number) => string;
  formatTime: (timestampMs: number) => string;
};

function translate(table: Table, key: MessageKey, vars?: Vars) {
  let text = table[key] ?? en[key];
  if (text.includes("|")) {
    const [one, other] = text.split("|");
    text = Number(vars?.count) === 1 ? one : other;
  }
  return vars ? text.replace(/\{(\w+)\}/g, (match, name: string) => name in vars ? String(vars[name]) : match) : text;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>(deviceLanguage);
  useEffect(() => {
    void AsyncStorage.getItem(languageStorageKey).then((stored) => {
      if (languages.some((item) => item.code === stored)) setLanguageState(stored as LanguageCode);
    }).catch(() => undefined);
  }, []);
  const value = useMemo<I18nValue>(() => {
    const table = languages.find((item) => item.code === language)?.table ?? en;
    const locale = language === "zh-Hans" ? "zh-CN" : "en";
    const t = (key: MessageKey, vars?: Vars) => translate(table, key, vars);
    return {
      language,
      setLanguage: (code) => {
        setLanguageState(code);
        void AsyncStorage.setItem(languageStorageKey, code).catch(() => undefined);
      },
      t,
      formatAgo: (timestampMs) => {
        const seconds = Math.max(0, (Date.now() - timestampMs) / 1000);
        if (seconds < 60) return t("agoNow");
        if (seconds < 3600) return t("agoMin", { n: Math.floor(seconds / 60) });
        if (seconds < 86_400) return t("agoHour", { n: Math.floor(seconds / 3600) });
        return t("agoDay", { n: Math.floor(seconds / 86_400) });
      },
      formatDateTime: (timestampMs) => new Date(timestampMs).toLocaleString(locale, { month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" }),
      formatTime: (timestampMs) => new Date(timestampMs).toLocaleTimeString(locale, { hour: "2-digit", minute: "2-digit" }),
    };
  }, [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
